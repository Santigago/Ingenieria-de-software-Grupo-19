async function registrarAuditoria({
    usuario_id = null,
    actor_usuario_id = null,
    evento_tipo,
    modulo = 'autenticacion',
    accion,
    resultado,
    detalle = null
}) {
    try {
        await db.query(
            `INSERT INTO public.bitacora_auditoria
                (usuario_id, actor_usuario_id, evento_tipo, modulo, accion, resultado, detalle)
             VALUES ($1, $2, $3, $4, $5, $6, $7)`,
            [usuario_id, actor_usuario_id, evento_tipo, modulo, accion, resultado, detalle]
        );
    } catch (error) {
        console.error('Error registrando evento en bitácora de auditoría:', error.message);
    }
}

