    producto_tipo_negocio varchar(20) NOT NULL DEFAULT 'comida',
    producto_tipo_control_stock varchar(20) NOT NULL DEFAULT 'lote',
    producto_estado varchar(20) NOT NULL DEFAULT 'activo',
    producto_motivo_baja text,
